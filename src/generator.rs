/// Split a container image reference into (name, optional_tag).
///
/// The tag separator is the last `:` that appears after the last `/`.
/// This correctly handles registry ports (e.g., `localhost:5000/image:tag`).
/// Returns `(full_ref, None)` when no tag is present or the ref already
/// contains a digest (`@`).
pub fn split_image_ref(image_ref: &str) -> (&str, Option<&str>) {
    // Digests are not tags — leave them alone
    if image_ref.contains('@') {
        return (image_ref, None);
    }

    let colon_search_start = image_ref.rfind('/').map(|p| p + 1).unwrap_or(0);

    match image_ref[colon_search_start..].find(':') {
        Some(offset) => {
            let colon_pos = colon_search_start + offset;
            (&image_ref[..colon_pos], Some(&image_ref[colon_pos + 1..]))
        }
        None => (image_ref, None),
    }
}

/// Returns the `--from=` argument for COPY instructions.
/// Uses inline image refs when stages are unnamed, named stage aliases otherwise.
fn copy_from_source(loaded: &LoadedFragment, use_named_stages: bool) -> String {
    if use_named_stages {
        format!("frag-{}", loaded.fragment.name)
    } else {
        let FragmentSource::Registry { ref image_ref } = loaded.source;
        image_ref.clone()
    }
}

/// `self_contained` emits context-relative COPY/mount forms instead of
/// registry references, for `--self-contained` output. Mutually exclusive
/// with `ocp` (enforced by the CLI's `conflicts_with`, not checked here).
pub fn generate_containerfile(
    manifest: &Manifest,
    fragments: &[LoadedFragment],
    base_digest: Option<&str>,
    ocp: bool,
    self_contained: bool,
    capabilities: &CapabilitySet,
) -> Result<String> {
    let mut out = String::new();
    let use_named_stages = fragments.iter().any(|f| f.resolved_digest.is_some());

    // Header (standalone only — OCP omits to stay under MachineOSConfig limits)
    if !ocp {
        writeln!(out, "# Generated by osfragment-assemble v0.1.0")?;
        writeln!(out, "# Manifest: {}", manifest.source_path)?;

        let frag_summary: Vec<String> = fragments.iter().map(|f| f.fragment.name.clone()).collect();
        writeln!(out, "# Fragments: {}", frag_summary.join(", "))?;

        // Resolved digests. Self-contained mode always resolves fragment
        // digests internally (materialization must pull deterministic
        // content regardless of --pin-digests, see process-docs), but
        // never prints them: no fragment registry reference may appear
        // anywhere in this mode's output, comments included.
        let has_digests = base_digest.is_some()
            || (!self_contained && fragments.iter().any(|f| f.resolved_digest.is_some()));
        if has_digests {
            writeln!(out, "# Resolved digests:")?;
            if let Some(d) = base_digest {
                writeln!(out, "#   base: {}@{}", manifest.base, d)?;
            }
            if !self_contained {
                for loaded in fragments {
                    let mf = &manifest.fragments[loaded.manifest_index];
                    if let Some(d) = &loaded.resolved_digest {
                        writeln!(out, "#   {}: {}@{}", loaded.fragment.name, mf.image, d)?;
                    }
                }
            }
        }

        // Compute override summary — detect file path collisions
        let mut path_owners: std::collections::HashMap<String, Vec<String>> =
            std::collections::HashMap::new();
        for loaded in fragments {
            for p in &loaded.tree_paths {
                if p.to_string_lossy().starts_with("tree/") {
                    let dest = p
                        .strip_prefix("tree")
                        .unwrap_or(p)
                        .to_string_lossy()
                        .to_string();
                    path_owners
                        .entry(dest)
                        .or_default()
                        .push(loaded.fragment.name.clone());
                }
            }
        }
        let collisions: Vec<_> = path_owners
            .iter()
            .filter(|(_, owners)| owners.len() > 1)
            .collect();
        if collisions.is_empty() {
            writeln!(out, "# Override summary: no file path collisions detected")?;
        } else {
            writeln!(
                out,
                "# Override summary: {} file path collision(s) detected",
                collisions.len()
            )?;
            for (path, owners) in &collisions {
                writeln!(
                    out,
                    "#   {} — written by: {} (last wins)",
                    path,
                    owners.join(", ")
                )?;
            }
        }
        writeln!(out)?;
    }

    // Fragment FROM stages (only when pinning digests, named stages for
    // readability). Self-contained mode never emits these: nothing in the
    // build context comes from a named stage, and no fragment registry
    // reference may appear in the output.
    if use_named_stages && !self_contained {
        if !ocp {
            writeln!(out, "# --- Fragment stages ---")?;
        }
        for loaded in fragments {
            let FragmentSource::Registry { ref image_ref } = loaded.source;
            writeln!(out, "FROM {} AS frag-{}", image_ref, loaded.fragment.name)?;
        }
        if !ocp {
            writeln!(out)?;
        }
    }

    // Main stage
    if ocp {
        writeln!(out, "FROM configs AS final")?;
    } else {
        writeln!(out, "# --- Base ---")?;
        let base_ref = if let Some(d) = base_digest {
            let (base_name, _tag) = split_image_ref(&manifest.base);
            format!("{}@{}", base_name, d)
        } else {
            manifest.base.clone()
        };
        writeln!(out, "FROM {}", base_ref)?;
    }
    if !ocp {
        writeln!(out)?;
    }

    // Repo files — must land before dnf install
    let has_repo_content = fragments
        .iter()
        .any(|f| f.tree_paths.iter().any(|p| is_repo_path(p)));
    if has_repo_content {
        if !ocp {
            writeln!(out, "# --- Repo files ---")?;
        }
        for loaded in fragments {
            let has_repo = loaded.tree_paths.iter().any(|p| is_repo_path(p));
            if !has_repo {
                continue;
            }
            if loaded
                .tree_paths
                .iter()
                .any(|p| p.to_string_lossy().contains("yum.repos.d"))
            {
                if self_contained {
                    writeln!(
                        out,
                        "COPY fragments/{}/tree/etc/yum.repos.d/ /etc/yum.repos.d/",
                        loaded.fragment.name
                    )?;
                } else {
                    let source = copy_from_source(loaded, use_named_stages);
                    writeln!(
                        out,
                        "COPY --from={} /fragment/tree/etc/yum.repos.d/ /etc/yum.repos.d/",
                        source
                    )?;
                }
            }
            if loaded
                .tree_paths
                .iter()
                .any(|p| p.to_string_lossy().contains("rpm-gpg"))
            {
                if self_contained {
                    writeln!(
                        out,
                        "COPY fragments/{}/tree/etc/pki/rpm-gpg/ /etc/pki/rpm-gpg/",
                        loaded.fragment.name
                    )?;
                } else {
                    let source = copy_from_source(loaded, use_named_stages);
                    writeln!(
                        out,
                        "COPY --from={} /fragment/tree/etc/pki/rpm-gpg/ /etc/pki/rpm-gpg/",
                        source
                    )?;
                }
            }
        }

        // Mirror rewrites (must follow the repo COPYs)
        for loaded in fragments {
            let mf = &manifest.fragments[loaded.manifest_index];
            if let Some(mirror_url) = &mf.mirror {
                let repo_files: Vec<_> = loaded
                    .tree_paths
                    .iter()
                    .filter(|p| p.to_string_lossy().contains("yum.repos.d"))
                    .filter_map(|p| {
                        p.file_name()
                            .map(|f| format!("/etc/yum.repos.d/{}", f.to_string_lossy()))
                    })
                    .collect();
                for repo_file in &repo_files {
                    writeln!(
                        out,
                        "RUN sed -i 's|^baseurl=.*|baseurl={}|; s|^metalink=|#metalink=|; s|^mirrorlist=|#mirrorlist=|' {}",
                        mirror_url, repo_file
                    )?;
                }
            }
        }
        if !ocp {
            writeln!(out)?;
        }
    }

    // Packages — required (fragment-declared) first, then manifest-selected
    let mut seen = std::collections::HashSet::new();
    let mut all_packages: Vec<String> = Vec::new();

    // Phase 1: fragment-declared required packages, in fragment order
    // (fragments are in manifest order)
    for loaded in fragments {
        for pkg in &loaded.fragment.packages.required {
            if seen.insert(pkg.clone()) {
                all_packages.push(pkg.clone());
            }
        }
    }

    // Phase 2: manifest-selected packages, in manifest order
    for mf in &manifest.fragments {
        for pkg in &mf.packages {
            if seen.insert(pkg.clone()) {
                all_packages.push(pkg.clone());
            }
        }
    }

    if !all_packages.is_empty() {
        if !ocp {
            writeln!(out, "# --- Packages ---")?;
        }
        writeln!(out, "RUN dnf install -y \\")?;
        for pkg in &all_packages {
            writeln!(out, "        {} \\", pkg)?;
        }
        writeln!(out, "    && dnf clean all \\")?;
        writeln!(
            out,
            "    && rm -rf /var/cache/dnf /var/log/dnf* /var/log/hawkey.log /var/lib/dnf/history.sqlite*"
        )?;
        if !ocp {
            writeln!(out)?;
        }
    }

    // Config files — after packages so fragment configs win over RPM defaults
    let has_config_content = fragments.iter().any(|f| {
        f.tree_paths
            .iter()
            .any(|p| p.to_string_lossy().starts_with("tree/") && !is_repo_path(p))
    });
    if has_config_content {
        if !ocp {
            writeln!(out, "# --- Config files ---")?;
        }
        for loaded in fragments {
            let has_non_repo = loaded
                .tree_paths
                .iter()
                .any(|p| p.to_string_lossy().starts_with("tree/") && !is_repo_path(p));
            if !has_non_repo {
                continue;
            }
            if self_contained {
                writeln!(out, "COPY fragments/{}/tree/ /", loaded.fragment.name)?;
            } else {
                let source = copy_from_source(loaded, use_named_stages);
                writeln!(out, "COPY --from={} /fragment/tree/ /", source)?;
            }
        }
        if !ocp {
            writeln!(out)?;
        }
    }

    // Hooks (must run after packages are installed)
    let hook_fragments: Vec<_> = fragments
        .iter()
        .filter(|f| !f.hook_paths.is_empty())
        .collect();
    if !hook_fragments.is_empty() {
        if !ocp {
            writeln!(out, "# --- Hooks ---")?;
        }
        for loaded in &hook_fragments {
            if self_contained {
                writeln!(
                    out,
                    "RUN --mount=type=bind,source=fragments/{}/hooks,target=/frag-hooks,z \\",
                    loaded.fragment.name
                )?;
            } else {
                let source = copy_from_source(loaded, use_named_stages);
                writeln!(
                    out,
                    "RUN --mount=type=bind,from={},source=/fragment/hooks,target=/frag-hooks,z \\",
                    source
                )?;
            }
            // The entrypoint is the only file the tool runs; anything else
            // under hooks/ is support material it can reach at the mount path.
            writeln!(out, "    /frag-hooks/entrypoint")?;
        }
        if !ocp {
            writeln!(out)?;
        }
    }

    // Phase: preset-apply (35) — requires systemd capability
    if capabilities.contains(&Capability::Systemd) {
        if !ocp {
            writeln!(out, "# Apply systemd presets from fragments")?;
        }
        writeln!(
            out,
            "RUN systemctl preset-all --preset-mode=enable-only 2>/dev/null || true"
        )?;
        if !ocp {
            writeln!(out)?;
        }
    }

    // Phase: validation (90) — requires bootc capability
    if capabilities.contains(&Capability::Bootc) {
        if !ocp {
            writeln!(out, "# --- Phase: validation (90) ---")?;
        }
        writeln!(out, "RUN bootc container lint")?;
    }

    Ok(out)
}

