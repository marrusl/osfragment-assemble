/// Comment emitted once above the credential build mounts in generated
/// output. The tool cannot know the build host at generate time, so this
/// in-file note is the primary channel for the subscribed-host caveat: it
/// travels with the Containerfile to wherever the build runs.
const CREDENTIAL_MOUNT_COMMENT: &str = "\
# Build mounts below supply credential material the build host may not\n\
# have. A subscribed RHEL host already injects its own entitlement into\n\
# every build step, so an entitlement fragment is redundant there and can\n\
# be omitted. Other credential mounts, such as mirror client certs or\n\
# proxy CA bundles, are still required regardless of host.";

/// Split a container image reference into (name, optional_tag).
///
/// The tag separator is the last `:` that appears after the last `/`.
/// This correctly handles registry ports (e.g., `localhost:5000/image:tag`).
/// Returns `(full_ref, None)` when no tag is present or the ref already
/// contains a digest (`@`).
pub fn split_image_ref(image_ref: &str) -> (&str, Option<&str>) {
    // Digests are not tags: leave them alone
    if image_ref.contains('@') {
        return (image_ref, None);
    }

    let colon_search_start = image_ref.rfind('/').map(|p| p + 1).unwrap_or(0);

    match image_ref[colon_search_start..].find(':') {
        Some(offset) => {
            let colon_pos = colon_search_start + offset;
            (&image_ref[..colon_pos], Some(&image_ref[colon_pos + 1..]))
        }
        None => (image_ref, None),
    }
}

/// Rewrite `image_ref` to name `digest`, dropping whatever tag or digest it
/// already carries.
///
/// `split_image_ref` deliberately returns a digest-bearing reference whole,
/// because a digest is not a tag, so it cannot on its own strip a tag from a
/// reference that carries both (`repo:tag@sha256:old`). This function strips
/// the digest first, then routes the remainder through `split_image_ref` to
/// drop any tag, so a bare tag, a bare digest, or both together all
/// canonicalize to `repository@digest`.
pub fn pin_to_digest(image_ref: &str, digest: &str) -> String {
    let without_digest = image_ref.split('@').next().unwrap_or(image_ref);
    let (repository, _tag) = split_image_ref(without_digest);
    format!("{}@{}", repository, digest)
}

/// Returns the `--from=` argument for COPY instructions.
/// Uses inline image refs when stages are unnamed, named stage aliases otherwise.
fn copy_from_source(loaded: &LoadedFragment, use_named_stages: bool) -> String {
    if use_named_stages {
        format!("frag-{}", loaded.fragment.name)
    } else {
        let FragmentSource::Registry { ref image_ref } = loaded.source;
        image_ref.clone()
    }
}

/// Emit a `RUN` whose leading `--mount` flag rides the `RUN ` line, each
/// further flag is a four-space-indented continuation line, and `command` is
/// the final line. The package step and every hook step both build their RUN
/// this way, so the two sites cannot drift on the continuation formatting.
///
/// `command` is written verbatim as the last line: pass a trailing `\` when
/// more lines follow it (the package step's `dnf install -y \`, continued by
/// the package list) and none when it is the whole command (a hook's
/// `/frag-hook/entrypoint`). With no flags the result is `RUN <command>`,
/// byte-identical to what an unmounted step emits.
fn write_mounted_run(out: &mut String, flags: &[String], command: &str) -> std::fmt::Result {
    match flags.split_first() {
        None => writeln!(out, "RUN {}", command),
        Some((first, rest)) => {
            writeln!(out, "RUN {} \\", first)?;
            for flag in rest {
                writeln!(out, "    {} \\", flag)?;
            }
            writeln!(out, "    {}", command)
        }
    }
}

/// `self_contained` emits context-relative COPY/mount forms instead of
/// registry references, for `--self-contained` output. Mutually exclusive
/// with `ocp` (enforced by the CLI's `conflicts_with`, not checked here).
pub fn generate_containerfile(
    manifest: &Manifest,
    fragments: &[LoadedFragment],
    base_digest: Option<&str>,
    ocp: bool,
    self_contained: bool,
) -> Result<String> {
    let mut out = String::new();
    let use_named_stages = fragments.iter().any(|f| f.resolved_digest.is_some());

    // Header (standalone only; OCP omits to stay under MachineOSConfig limits)
    if !ocp {
        writeln!(out, "# Generated by osfragment-assemble v0.1.0")?;
        writeln!(out, "# Manifest: {}", manifest.source_path)?;

        let frag_summary: Vec<String> = fragments
            .iter()
            .map(|f| f.fragment.name.to_string())
            .collect();
        writeln!(out, "# Fragments: {}", frag_summary.join(", "))?;

        // Resolved digests. Self-contained mode always resolves fragment
        // digests internally (materialization must pull deterministic
        // content regardless of --pin-digests, see process-docs), but
        // never prints them: no fragment registry reference may appear
        // anywhere in this mode's output, comments included.
        let has_digests = base_digest.is_some()
            || (!self_contained && fragments.iter().any(|f| f.resolved_digest.is_some()));
        if has_digests {
            writeln!(out, "# Resolved digests:")?;
            if let Some(d) = base_digest {
                writeln!(out, "#   base: {}@{}", manifest.base, d)?;
            }
            if !self_contained {
                for loaded in fragments {
                    let mf = &manifest.fragments[loaded.manifest_index];
                    if let Some(d) = &loaded.resolved_digest {
                        writeln!(out, "#   {}: {}@{}", loaded.fragment.name, mf.image, d)?;
                    }
                }
            }
        }

        // Compute override summary: detect file path collisions
        let mut path_owners: std::collections::HashMap<String, Vec<String>> =
            std::collections::HashMap::new();
        for loaded in fragments {
            for p in &loaded.tree_paths {
                if p.to_string_lossy().starts_with("tree/") {
                    let dest = p
                        .strip_prefix("tree")
                        .unwrap_or(p)
                        .to_string_lossy()
                        .to_string();
                    path_owners
                        .entry(dest)
                        .or_default()
                        .push(loaded.fragment.name.to_string());
                }
            }
        }
        let collisions: Vec<_> = path_owners
            .iter()
            .filter(|(_, owners)| owners.len() > 1)
            .collect();
        if collisions.is_empty() {
            writeln!(out, "# Override summary: no file path collisions detected")?;
        } else {
            writeln!(
                out,
                "# Override summary: {} file path collision(s) detected",
                collisions.len()
            )?;
            for (path, owners) in &collisions {
                writeln!(
                    out,
                    "#   {}: written by {} (last wins)",
                    path,
                    owners.join(", ")
                )?;
            }
        }
        writeln!(out)?;
    }

    // Fragment FROM stages (only when pinning digests, named stages for
    // readability). Self-contained mode never emits these: nothing in the
    // build context comes from a named stage, and no fragment registry
    // reference may appear in the output.
    // A fragment consisting of metadata and mount/ alone is excluded: its
    // reference is always emitted inline on the package RUN, so a stage for
    // it would be consumed by nothing and would spend characters against the
    // MachineOSConfig content limit for no reader.
    let staged: Vec<&LoadedFragment> = fragments.iter().filter(|f| !f.is_pure_mount()).collect();
    if use_named_stages && !self_contained && !staged.is_empty() {
        if !ocp {
            writeln!(out, "# --- Fragment stages ---")?;
        }
        for loaded in &staged {
            let FragmentSource::Registry { ref image_ref } = loaded.source;
            writeln!(out, "FROM {} AS frag-{}", image_ref, loaded.fragment.name)?;
        }
        if !ocp {
            writeln!(out)?;
        }
    }

    // Main stage
    if ocp {
        writeln!(out, "FROM configs AS final")?;
    } else {
        writeln!(out, "# --- Base ---")?;
        let base_ref = if let Some(d) = base_digest {
            pin_to_digest(&manifest.base, d)
        } else {
            manifest.base.clone()
        };
        writeln!(out, "FROM {}", base_ref)?;
    }
    if !ocp {
        writeln!(out)?;
    }

    // Repo files: must land before dnf install
    let has_repo_content = fragments
        .iter()
        .any(|f| f.tree_paths.iter().any(|p| is_repo_path(p)));
    if has_repo_content {
        if !ocp {
            writeln!(out, "# --- Repo files ---")?;
        }
        for loaded in fragments {
            let has_repo = loaded.tree_paths.iter().any(|p| is_repo_path(p));
            if !has_repo {
                continue;
            }
            if loaded
                .tree_paths
                .iter()
                .any(|p| p.to_string_lossy().contains("yum.repos.d"))
            {
                if self_contained {
                    writeln!(
                        out,
                        "COPY fragments/{}/tree/etc/yum.repos.d/ /etc/yum.repos.d/",
                        loaded.fragment.name
                    )?;
                } else {
                    let source = copy_from_source(loaded, use_named_stages);
                    writeln!(
                        out,
                        "COPY --from={} /fragment/tree/etc/yum.repos.d/ /etc/yum.repos.d/",
                        source
                    )?;
                }
            }
            if loaded
                .tree_paths
                .iter()
                .any(|p| p.to_string_lossy().contains("rpm-gpg"))
            {
                if self_contained {
                    writeln!(
                        out,
                        "COPY fragments/{}/tree/etc/pki/rpm-gpg/ /etc/pki/rpm-gpg/",
                        loaded.fragment.name
                    )?;
                } else {
                    let source = copy_from_source(loaded, use_named_stages);
                    writeln!(
                        out,
                        "COPY --from={} /fragment/tree/etc/pki/rpm-gpg/ /etc/pki/rpm-gpg/",
                        source
                    )?;
                }
            }
        }

        // Mirror rewrites (must follow the repo COPYs)
        for loaded in fragments {
            let mf = &manifest.fragments[loaded.manifest_index];
            if let Some(mirror_url) = &mf.mirror {
                let repo_files: Vec<_> = loaded
                    .tree_paths
                    .iter()
                    .filter(|p| p.to_string_lossy().contains("yum.repos.d"))
                    .filter_map(|p| {
                        p.file_name()
                            .map(|f| format!("/etc/yum.repos.d/{}", f.to_string_lossy()))
                    })
                    .collect();
                for repo_file in &repo_files {
                    writeln!(
                        out,
                        "RUN sed -i 's|^baseurl=.*|baseurl={}|; s|^metalink=|#metalink=|; s|^mirrorlist=|#mirrorlist=|' {}",
                        mirror_url, repo_file
                    )?;
                }
            }
        }
        if !ocp {
            writeln!(out)?;
        }
    }

    // Packages: required (fragment-declared) first, then manifest-selected
    let mut seen = std::collections::HashSet::new();
    let mut all_packages: Vec<String> = Vec::new();

    // Phase 1: fragment-declared required packages, in fragment order
    // (fragments are in manifest order)
    for loaded in fragments {
        for pkg in &loaded.fragment.packages.required {
            if seen.insert(pkg.clone()) {
                all_packages.push(pkg.clone());
            }
        }
    }

    // Phase 2: manifest-selected packages, in manifest order
    for mf in &manifest.fragments {
        for pkg in &mf.packages {
            if seen.insert(pkg.clone()) {
                all_packages.push(pkg.clone());
            }
        }
    }

    // Build mounts. The package phase already copies the config that belongs
    // in the image; this is its second verb, mounting the material that must
    // not persist. One flag per derived mount point, fragments in manifest
    // order, and always inline: a build-mount reference is never a named
    // stage, including under --pin-digests.
    let mut mount_flags: Vec<String> = Vec::new();
    for loaded in fragments {
        let FragmentSource::Registry { ref image_ref } = loaded.source;
        for point in &loaded.mount_points {
            mount_flags.push(if self_contained {
                // No registry reference may appear in this mode's output, so
                // the material is read from the context instead, the same
                // pattern hooks use.
                point.mount_flag(None, &point.context_source(&loaded.fragment.name))
            } else {
                point.mount_flag(Some(image_ref), &point.layer_source())
            });
        }
    }

    if !all_packages.is_empty() {
        if !ocp {
            writeln!(out, "# --- Packages ---")?;
        }
        // The credential mounts ride the package RUN and, below, every hook
        // RUN. The comment sits once above their first appearance; with a
        // package step that is here.
        if !ocp && !mount_flags.is_empty() {
            writeln!(out, "{}", CREDENTIAL_MOUNT_COMMENT)?;
        }
        // With no mounts this is byte-identical to what every existing
        // manifest already generates: `RUN dnf install -y \`.
        write_mounted_run(&mut out, &mount_flags, "dnf install -y \\")?;
        for pkg in &all_packages {
            writeln!(out, "        {} \\", pkg)?;
        }
        writeln!(out, "    && dnf clean all \\")?;
        writeln!(
            out,
            "    && rm -rf /var/cache/dnf /var/log/dnf* /var/log/hawkey.log /var/lib/dnf/history.sqlite* \\"
        )?;
        // Residue from dnf's plugins rather than from dnf itself: the
        // subscription-manager plugin writes /run/rhsm, /var/log/rhsm and
        // /var/lib/rhsm on any invocation, the selinux-policy scriptlets write
        // /run/selinux-policy, and ldconfig leaves an aux-cache behind. None
        // exist in a stock bootc base and each one costs a lint warning.
        writeln!(
            out,
            "    && rm -rf /run/rhsm /run/selinux-policy /var/log/rhsm /var/lib/rhsm /var/cache/ldconfig/aux-cache"
        )?;
        if !ocp {
            writeln!(out)?;
        }
    }

    // Config files: after packages so fragment configs win over RPM defaults
    let has_config_content = fragments.iter().any(|f| {
        f.tree_paths
            .iter()
            .any(|p| p.to_string_lossy().starts_with("tree/") && !is_repo_path(p))
    });
    if has_config_content {
        if !ocp {
            writeln!(out, "# --- Config files ---")?;
        }
        for loaded in fragments {
            let has_non_repo = loaded
                .tree_paths
                .iter()
                .any(|p| p.to_string_lossy().starts_with("tree/") && !is_repo_path(p));
            if !has_non_repo {
                continue;
            }
            if self_contained {
                writeln!(out, "COPY fragments/{}/tree/ /", loaded.fragment.name)?;
            } else {
                let source = copy_from_source(loaded, use_named_stages);
                writeln!(out, "COPY --from={} /fragment/tree/ /", source)?;
            }
        }
        if !ocp {
            writeln!(out)?;
        }
    }

    // Hooks (must run after packages are installed)
    let hook_fragments: Vec<_> = fragments
        .iter()
        .filter(|f| !f.hook_paths.is_empty())
        .collect();
    if !hook_fragments.is_empty() {
        if !ocp {
            writeln!(out, "# --- Hooks ---")?;
        }
        // The credential comment normally rides the package step; with no
        // package step, the hook RUNs are where the mounts first appear, so
        // it sits here instead. The package-step guard above and this one are
        // mutually exclusive, so the comment is emitted exactly once.
        if !ocp && !mount_flags.is_empty() && all_packages.is_empty() {
            writeln!(out, "{}", CREDENTIAL_MOUNT_COMMENT)?;
        }
        for loaded in &hook_fragments {
            // The credential build mounts lead the RUN line, matching the
            // package step, so a hook that shells out to dnf against the base
            // repos authenticates exactly as the package step does. The
            // hook's own bind mount is the final flag, immediately above the
            // `/frag-hook/entrypoint` invocation that uses it. The
            // mount_flags vector is reused verbatim and never routed through
            // a named stage: a build-mount reference is always inline, and a
            // pure-mount fragment has no stage to reference.
            let hooks_mount = if self_contained {
                format!(
                    "--mount=type=bind,source=fragments/{}/hook,target=/frag-hook,z",
                    loaded.fragment.name
                )
            } else {
                let source = copy_from_source(loaded, use_named_stages);
                format!(
                    "--mount=type=bind,from={},source=/fragment/hook,target=/frag-hook,z",
                    source
                )
            };
            let mut hook_flags = mount_flags.clone();
            hook_flags.push(hooks_mount);
            // The entrypoint is the only file the tool runs; anything else
            // under hook/ is support material it can reach at the mount path.
            write_mounted_run(&mut out, &hook_flags, "/frag-hook/entrypoint")?;
        }
        if !ocp {
            writeln!(out)?;
        }
    }

    // Phase: preset-apply (35). Unconditional: every base this tool targets
    // is a bootc image, which carries systemd.
    if !ocp {
        writeln!(out, "# Apply systemd presets from fragments")?;
    }
    writeln!(
        out,
        "RUN systemctl preset-all --preset-mode=enable-only 2>/dev/null || true"
    )?;
    if !ocp {
        writeln!(out)?;
    }

    // Phase: validation (90). Unconditional: on a base without bootc this
    // step fails the build, which is the supported way to find out.
    if !ocp {
        writeln!(out, "# --- Phase: validation (90) ---")?;
    }
    writeln!(out, "RUN bootc container lint")?;

    Ok(out)
}

