        let output = generate_containerfile(
            &manifest,
            &[epel],
            Some("sha256:base123"),
            &empty_dedup(),
            true,
        )
        .unwrap();
        // Named stages before FROM configs AS final
        assert!(output.contains("FROM quay.io/test/epel@sha256:aaa111 AS frag-epel"));
